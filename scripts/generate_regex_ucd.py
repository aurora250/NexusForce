#!/usr/bin/env python3
"""Regenerate src/core/string/regex_ucd_tables.hpp.

The generated header holds the Unicode general category ranges and the simple
case mapping tables the builtin regular expression engine relies on.  Run it
after bumping the Unicode version used by Python's unicodedata module:

    python scripts/generate_regex_ucd.py
"""

import sys
import unicodedata

MAX_CODE_POINT = 0x10FFFF

CATEGORIES = [
    "Lu", "Ll", "Lt", "Lm", "Lo",
    "Mn", "Mc", "Me",
    "Nd", "Nl", "No",
    "Pc", "Pd", "Ps", "Pe", "Pi", "Pf", "Po",
    "Sm", "Sc", "Sk", "So",
    "Zs", "Zl", "Zp",
    "Cc", "Cf", "Co", "Cs", "Cn",
]

CATEGORY_INDEX = {name: index + 1 for index, name in enumerate(CATEGORIES)}


def category_ranges():
    ranges = []
    start = 0
    current = unicodedata.category(chr(0))
    for code_point in range(1, MAX_CODE_POINT + 1):
        category = unicodedata.category(chr(code_point))
        if category != current:
            ranges.append((start, code_point - 1, current))
            start = code_point
            current = category
    ranges.append((start, MAX_CODE_POINT, current))
    return ranges


def single_char_map(mapper):
    pairs = []
    for code_point in range(MAX_CODE_POINT + 1):
        mapped = mapper(chr(code_point))
        if len(mapped) == 1 and ord(mapped) != code_point:
            pairs.append((code_point, ord(mapped)))
    return pairs


UNEMITTED = ("Cn", "Cs")


def emit_ranges(lines, ranges):
    for begin, end, category in ranges:
        if category in UNEMITTED:
            continue
        lines.append("    {0x%05XU, 0x%05XU, %2dU}," % (begin, end, CATEGORY_INDEX[category]))


def emit_pairs(lines, pairs):
    row = []
    for source, target in pairs:
        row.append("{0x%05XU, 0x%05XU}" % (source, target))
        if len(row) == 4:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")


def main():
    ranges = category_ranges()
    lower = single_char_map(str.lower)
    upper = single_char_map(str.upper)

    lines = []
    lines.append("// Generated by scripts/generate_regex_ucd.py -- do not edit by hand.")
    lines.append("// Unicode version: %s" % unicodedata.unidata_version)
    lines.append("")
    lines.append("#ifndef NEFORCE_CORE_STRING_REGEX_UCD_TABLES_HPP__")
    lines.append("#define NEFORCE_CORE_STRING_REGEX_UCD_TABLES_HPP__")
    lines.append("#include <NeForce/core/typeinfo/types.hpp>")
    lines.append("NEFORCE_BEGIN_NAMESPACE__")
    lines.append("namespace regex_ucd {")
    lines.append("")
    lines.append("    struct range_entry {")
    lines.append("        uint32_t start;")
    lines.append("        uint32_t end;")
    lines.append("        uint16_t category;")
    lines.append("    };")
    lines.append("")
    lines.append("    struct case_entry {")
    lines.append("        uint32_t source;")
    lines.append("        uint32_t target;")
    lines.append("    };")
    lines.append("")
    lines.append("    constexpr uint16_t category_none = 0;")
    lines.append("    constexpr uint16_t category_cn = %d;" % CATEGORY_INDEX["Cn"])
    lines.append("    constexpr uint16_t category_ll = %d;" % CATEGORY_INDEX["Ll"])
    lines.append("    constexpr uint16_t category_lu = %d;" % CATEGORY_INDEX["Lu"])
    lines.append("    constexpr uint16_t category_lt = %d;" % CATEGORY_INDEX["Lt"])
    lines.append("    constexpr uint16_t category_mn = %d;" % CATEGORY_INDEX["Mn"])
    lines.append("    constexpr uint16_t category_mc = %d;" % CATEGORY_INDEX["Mc"])
    lines.append("    constexpr uint16_t category_me = %d;" % CATEGORY_INDEX["Me"])
    lines.append("    constexpr uint16_t category_nd = %d;" % CATEGORY_INDEX["Nd"])
    lines.append("    constexpr uint16_t category_cc = %d;" % CATEGORY_INDEX["Cc"])
    lines.append("")
    lines.append("    constexpr range_entry ranges[] = {")
    emit_ranges(lines, ranges)
    lines.append("    };")
    lines.append("")
    lines.append("    constexpr case_entry lower_map[] = {")
    emit_pairs(lines, lower)
    lines.append("    };")
    lines.append("")
    lines.append("    constexpr case_entry upper_map[] = {")
    emit_pairs(lines, upper)
    lines.append("    };")
    lines.append("")
    lines.append("} // namespace regex_ucd")
    lines.append("NEFORCE_END_NAMESPACE__")
    lines.append("#endif // NEFORCE_CORE_STRING_REGEX_UCD_TABLES_HPP__")
    lines.append("")

    with open("src/core/string/regex_ucd_tables.hpp", "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines) + "\n")

    sys.stderr.write("ranges=%d lower=%d upper=%d lines=%d\n" % (len(ranges), len(lower), len(upper), len(lines)))


if __name__ == "__main__":
    main()
